def snapshot(path,limit):
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK|os.O_CLOEXEC)
    try:
        before=os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or before.st_size>limit:raise ValueError('input role')
        data=bytearray()
        while True:
            part=os.read(fd,min(4096,limit+1-len(data)))
            if not part:break
            data.extend(part)
            if len(data)>limit:raise ValueError('input bound')
        pin=lambda st:(st.st_dev,st.st_ino,st.st_size,st.st_mtime_ns,st.st_ctime_ns)
        if len(data)!=before.st_size or pin(before)!=pin(os.fstat(fd)) or pin(before)!=pin(path.lstat()):raise ValueError('input snapshot')
        return bytes(data)
    finally:os.close(fd)


